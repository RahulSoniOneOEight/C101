#!/usr/bin/env python3
"""Rebuild the CHG-060 image display-fitness evidence and TypeScript fixture."""

from __future__ import annotations

import argparse
import concurrent.futures
import io
import json
import math
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import requests
from PIL import Image, ImageStat

DEFAULT_API = (
    "https://api-staging.pinakaplay.cloud/v1/products"
    "?limit=250&offset=0&catalogue_import=CHG-049"
)
WEIGHTS = {
    "minimum_dimension": 0.32,
    "pixel_area": 0.13,
    "square_card_aspect_fit": 0.16,
    "non_white_subject_coverage": 0.13,
    "luminance_tonal_range": 0.10,
    "edge_sharpness": 0.08,
    "source_url_provenance": 0.08,
}


def score_product(product: dict) -> dict:
    response = None
    for attempt in range(3):
        try:
            response = requests.get(product["thumbnail"], timeout=(10, 60))
            response.raise_for_status()
            break
        except requests.RequestException:
            if attempt == 2:
                raise
            time.sleep(attempt + 1)
    assert response is not None
    image = Image.open(io.BytesIO(response.content)).convert("RGB")
    width, height = image.size
    sample = image.copy()
    sample.thumbnail((256, 256))
    pixels = np.asarray(sample, dtype=np.float32)
    gray = pixels.mean(axis=2)

    horizontal_edges = np.diff(gray, axis=1)
    vertical_edges = np.diff(gray, axis=0)
    sharpness = float((horizontal_edges.var() + vertical_edges.var()) / 2)
    subject_coverage = float(np.mean(np.min(pixels, axis=2) < 245))
    tonal_range = float(ImageStat.Stat(sample.convert("L")).stddev[0])
    aspect_ratio = width / height

    factors = {
        "minimum_dimension": min(min(width, height) / 800.0, 1.0),
        "pixel_area": min((width * height) / 1_000_000.0, 1.0),
        "square_card_aspect_fit": max(
            0.0,
            1.0 - abs(math.log(max(aspect_ratio, 0.01))) / math.log(3.0),
        ),
        "non_white_subject_coverage": min(subject_coverage / 0.55, 1.0),
        "luminance_tonal_range": min(tonal_range / 64.0, 1.0),
        "edge_sharpness": min(sharpness / 1200.0, 1.0),
        "source_url_provenance": 1.0
        if (product.get("metadata") or {}).get("source_url")
        else 0.0,
    }
    score = round(100 * sum(WEIGHTS[key] * value for key, value in factors.items()))
    return {
        "id": product["id"],
        "title": product["title"],
        "category": (product.get("metadata") or {}).get("category_l1"),
        "width": width,
        "height": height,
        "score": score,
        "source_url_present": bool((product.get("metadata") or {}).get("source_url")),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--api", default=DEFAULT_API)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--typescript", type=Path, required=True)
    args = parser.parse_args()

    payload = requests.get(args.api, timeout=60).json()
    products = payload.get("products", [])
    if payload.get("count") != 233 or len(products) != 233:
        raise SystemExit(f"Expected 233 CHG-049 products, got {payload.get('count')}/{len(products)}")

    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        rows = list(pool.map(score_product, products))
    rows.sort(key=lambda row: (-row["score"], row["title"].lower(), row["id"]))

    manifest = {
        "change_id": "CHG-060",
        "catalogue_import": "CHG-049",
        "generated_at_utc": datetime.now(timezone.utc).date().isoformat(),
        "fixture_only": True,
        "formula": WEIGHTS,
        "count": len(rows),
        "products": rows,
    }
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )

    lines = [
        "/**",
        " * GENERATED by CHG-060 from all 233 persistent CHG-049 thumbnails.",
        " * Display-fitness fixture only; not a production DAM quality judgement.",
        " */",
        "export const chg049ImageQualityScores: Readonly<Record<string, number>> = Object.freeze({",
    ]
    lines.extend(
        f'  "{row["id"]}": {row["score"]},' for row in sorted(rows, key=lambda row: row["id"])
    )
    lines.extend(["});", ""])
    args.typescript.parent.mkdir(parents=True, exist_ok=True)
    args.typescript.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
